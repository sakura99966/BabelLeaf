import { describe, expect, it } from 'vitest';
import {
  createDictionaryContent,
  sanitizeDictionaryCss,
} from '@/services/dictionaries/safeDictionaryContent';

describe('local dictionary rendering boundary', () => {
  it('removes executable elements and all event attributes before live DOM use', () => {
    const body = createDictionaryContent(
      '<p onclick="alert(1)">definition</p><img src="data:,x" onerror="alert(1)">' +
        '<iframe srcdoc="<script>alert(1)</script>"></iframe><svg onload="alert(1)"></svg>' +
        '<script>alert(1)</script><form action="https://invalid.example/"></form>',
    );
    expect(body.textContent).toContain('definition');
    expect(body.querySelector('script,iframe,svg,form,[onclick],[onerror],[onload]')).toBeNull();
    expect(body.querySelector('[src],[srcset],[srcdoc]')).toBeNull();
  });

  it('keeps local MDict resources inert and rejects remote, file and forged blob resources', () => {
    const body = createDictionaryContent(
      '<img src="/images/local.png"><img src="https://invalid.example/x">' +
        '<img src="blob:forged"><img src="file:///x"><link rel="stylesheet" href="local.css">' +
        '<link rel="stylesheet" href="//invalid.example/x.css">',
      { mdict: true },
    );
    expect(body.querySelector('img')?.getAttribute('data-dict-image')).toBe('/images/local.png');
    expect(body.querySelectorAll('[data-dict-image]')).toHaveLength(1);
    expect(body.querySelectorAll('[data-dict-stylesheet]')).toHaveLength(1);
    expect(body.querySelector('[src],[srcset],link[href]')).toBeNull();
  });

  it('parses only an entire known audio handler and never trusts supplied data attributes', () => {
    const body = createDictionaryContent(
      '<img onclick="v0r.v(this,\'local/key\')">' +
        '<img onclick="v0r.v(this,\'local/key\');alert(1)">' +
        '<img data-dict-audio-key="forged" data-mdd-audio="https://invalid.example/">',
      { mdict: true },
    );
    expect(body.querySelectorAll('[data-dict-audio-key]')).toHaveLength(1);
    expect(body.querySelector('[data-dict-audio-key]')?.getAttribute('data-dict-audio-key')).toBe(
      'local/key',
    );
    expect(body.querySelector('[onclick],[data-mdd-audio]')).toBeNull();
  });

  it('preserves structural markup, safe links and local formatting', () => {
    const body = createDictionaryContent(
      '<h2 id="word">word</h2><p class="meaning" style="color: red; font-weight: bold">meaning</p>' +
        '<a href="entry://next">next</a><a href="sound://local.mp3">sound</a>' +
        '<a href="javascript:alert(1)">bad</a><a href="file:///private">file</a>',
    );
    expect(body.querySelector('h2')?.textContent).toBe('word');
    expect(body.querySelector('p')?.style.color).toBe('red');
    expect(body.querySelector('p')?.style.fontWeight).toBe('bold');
    expect(body.querySelectorAll('a[href]')).toHaveLength(2);
  });

  it.each([
    '@import "https://invalid.example/style"; p{color:red}',
    'p{background:image-set("https://invalid.example/x" 1x)}',
    'p{background:u\\72l(https://invalid.example/x)}',
    'p{width:expression(alert(1))}',
  ])('fails closed on unsupported executable/network CSS: %s', (css) => {
    expect(sanitizeDictionaryCss(css, [])).toBe('');
  });

  it('keeps ordinary styles but only permits object URLs generated by this provider', () => {
    expect(sanitizeDictionaryCss('p { color: red; }', [])).toContain('color: red');
    expect(
      sanitizeDictionaryCss('p{background:url("blob:local-ok")}', ['blob:local-ok']),
    ).toContain('blob:local-ok');
    expect(sanitizeDictionaryCss('p{background:url("blob:forged")}', [])).not.toContain(
      'blob:forged',
    );
    expect(sanitizeDictionaryCss('p{background:url("relative.png")}', [])).not.toContain(
      'relative.png',
    );
    expect(sanitizeDictionaryCss('p{background:url(https://invalid.example/x)}', [])).not.toContain(
      'invalid.example',
    );
  });
});
